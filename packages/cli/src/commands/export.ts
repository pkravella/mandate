import { stringify } from "yaml";
import { compileGhAw, GH_AW_VERSION } from "@mandate-dev/compiler";
import { mandateHash, proofOf } from "@mandate-dev/schema";
import type { AuthorityDeps } from "../authority.js";
import { renderRejections } from "../diff.js";
import { prepareMandate, type PrepareArgs } from "../prepare.js";

/**
 * `mandate export gh-aw` -- a validated mandate as the frontmatter of a GitHub
 * Agentic Workflows workflow. See compiler/src/ghaw.ts for what maps and what
 * is refused.
 *
 * The mandate is validated first, exactly as `serve` and `run` validate it:
 * an export of a mandate nothing proved inside the ceiling would carry
 * Mandate's name on authority nobody checked.
 *
 * stdout is the workflow block and nothing else, so it can be redirected into
 * a file; every diagnostic goes to `err`. Exit 0 exported, 1 refused (by the
 * validator, or because gh-aw cannot hold it), 2 bad input.
 */
export async function runExportGhAw(
  args: PrepareArgs, out: (s: string) => void, err: (s: string) => void, deps: AuthorityDeps = {},
): Promise<number> {
  const prepared = await prepareMandate(args, deps);
  if (!prepared.ok) {
    if (prepared.code === 1) {
      err(renderRejections(prepared.rejections, prepared.proposed));
      err(prepared.provenance);
      err("Nothing was exported.");
      return 1;
    }
    err(prepared.message);
    return 2;
  }
  err(prepared.provenance);

  const result = compileGhAw(prepared.mandate);
  if (!result.ok) {
    err(`Not exportable to gh-aw ${GH_AW_VERSION} without granting more than the mandate does:`);
    for (const r of result.refusals) {
      err(`  - ${r.grant === undefined ? "" : `grant #${r.grant} (${r.action ?? "?"}): `}${r.reason}`);
    }
    err("Nothing was exported.");
    return 1;
  }

  const proof = proofOf(prepared.mandate);
  const m = prepared.mandate;
  const header = [
    `Generated by \`mandate export gh-aw\` for gh-aw ${GH_AW_VERSION} from mandate ${m.mandate} `
    + `(sha256 ${mandateHash(m)}),`,
    `validated against ceiling ${proof.ceilingId} (sha256 ${proof.ceilingSha256}) for ${m.requestedBy}, `
    + `whose level was ${prepared.verified ? "read from GitHub" : "asserted, not verified"}.`,
    `Commit this as a workflow in ${result.repo}, put the agent's instructions below the closing ---, `
    + "then run `gh aw compile`.",
    "These limits hold for every run of the workflow: it is a template for a kind of task, not one "
    + "task's mandate.",
    "The trigger is workflow_dispatch, which only people with write access can fire. A trigger an "
    + "outsider can fire (issues, issue_comment) puts their text in front of the agent: change it "
    + "deliberately.",
    ...(result.narrowings.length === 0 ? [] : [
      "Narrower than the mandate:",
      ...result.narrowings.map((n) => `  - ${n}`),
    ]),
    "Not from the mandate:",
    ...result.beyondMandate.map((n) => `  - ${n}`),
  ];
  const body = stringify({ on: { workflow_dispatch: null }, ...result.frontmatter }, { nullStr: "" });
  out(["---", ...header.map((l) => `# ${l}`), body.trimEnd(), "---"].join("\n"));
  return 0;
}
